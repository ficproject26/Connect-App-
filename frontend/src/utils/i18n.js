export const getStoredLanguage = () => {
  try {
    if (typeof window !== 'undefined') {
      const stored = localStorage.getItem('connect_auth_lang') || localStorage.getItem('connect_lang');
      if (stored && TRANSLATIONS[stored]) return stored;
    }
  } catch (e) {}
  return 'en';
};

export const setStoredLanguage = (langCode) => {
  try {
    if (typeof window !== 'undefined' && TRANSLATIONS[langCode]) {
      localStorage.setItem('connect_auth_lang', langCode);
      localStorage.setItem('connect_lang', langCode);
    }
  } catch (e) {}
};

export const t = (key, lang = 'en') => {
  const currentLangDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return currentLangDict[key] || TRANSLATIONS.en[key] || key;
};
